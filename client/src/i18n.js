/** Current UI locale. Set via `setLocale()` (language toggle). */
let currentLocale = "en";

/**
 * Set the active locale for the whole site.
 * @param {string} locale - "en" or "tr"
 */
export function setLocale(locale) {
  currentLocale = locale === "tr" ? "tr" : "en";
}

/**
 * Look up a translated string by key.
 * @param {string} key
 * @returns {string}
 */
export function t(key) {
  return (KEYS[key] && KEYS[key][currentLocale]) || KEYS[key].en || key;
}

/** Returns the list of currently available locales. */
export function locales() {
  return ["en", "tr"];
}

/** Current locale getter (useful for the date picker). */
export function locale() {
  return currentLocale;
}
